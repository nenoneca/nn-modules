static inline uint16_t fcs16(uint16_t fcs, uint8_t b)
{
	return (fcs >> 8) ^ fcs16_tab[(fcs ^ b) & 0xff];
}

static int emit_byte(uint8_t **p, uint8_t *end, uint8_t b)
{
	if (b == HDLC_FLAG || b == HDLC_ESCAPE) {
		if (*p + 2 > end) {
			return -1;
		}
		*(*p)++ = HDLC_ESCAPE;
		*(*p)++ = b ^ 0x20;
	} else {
		if (*p + 1 > end) {
			return -1;
		}
		*(*p)++ = b;
	}
	return 0;
}

int hdlc_encode(const uint8_t *payload, size_t payload_len,
		uint8_t *out_buf, size_t out_cap)
{
	uint8_t *p = out_buf;
	uint8_t *end = out_buf + out_cap;
	uint16_t fcs = HDLC_FCS_INIT;

	if (out_cap < 4) {
		return -1;
	}
	*p++ = HDLC_FLAG;

	for (size_t i = 0; i < payload_len; i++) {
		uint8_t b = payload[i];
		fcs = fcs16(fcs, b);
		if (emit_byte(&p, end, b) < 0) {
			return -1;
		}
	}

	fcs ^= 0xFFFF;
	if (emit_byte(&p, end, (uint8_t)(fcs & 0xff)) < 0) {
		return -1;
	}
	if (emit_byte(&p, end, (uint8_t)(fcs >> 8)) < 0) {
		return -1;
	}

	if (p + 1 > end) {
		return -1;
	}
	*p++ = HDLC_FLAG;

	return (int)(p - out_buf);
}

void hdlc_decoder_init(struct hdlc_decoder *d,
		       void (*on_frame)(const uint8_t *, size_t, void *),
		       void *user)
{
	d->len = 0;
	d->fcs = HDLC_FCS_INIT;
	d->in_escape = false;
	d->in_sync = false;
	d->on_frame = on_frame;
	d->user = user;
}

static void frame_complete(struct hdlc_decoder *d)
{
	if (d->len < 2) {
		/* Empty flag or too short — ignore. */
		d->len = 0;
		d->fcs = HDLC_FCS_INIT;
		d->in_escape = false;
		return;
	}

	if (d->fcs == HDLC_FCS_GOOD) {
		if (d->on_frame) {
			/* Strip trailing 2-byte FCS. */
			d->on_frame(d->buf, d->len - 2, d->user);
		}
	} else {
		LOG_WRN("hdlc: bad FCS 0x%04x (len=%zu)", d->fcs, d->len);
	}

	d->len = 0;
	d->fcs = HDLC_FCS_INIT;
	d->in_escape = false;
}

void hdlc_decode_byte(struct hdlc_decoder *d, uint8_t b)
{
	if (b == HDLC_FLAG) {
		if (d->in_sync && d->len > 0) {
			frame_complete(d);
		} else {
			/* Leading flag or empty frame — reset and arm. */
			d->len = 0;
			d->fcs = HDLC_FCS_INIT;
			d->in_escape = false;
		}
		d->in_sync = true;
		return;
	}

	if (!d->in_sync) {
		return; /* Ignore garbage before first flag. */
	}

	if (b == HDLC_ESCAPE) {
		d->in_escape = true;
		return;
	}

	if (d->in_escape) {
		b ^= 0x20;
		d->in_escape = false;
	}

	if (d->len >= sizeof(d->buf)) {
		LOG_WRN("hdlc: frame overflow, dropping");
		d->in_sync = false;
		d->len = 0;
		d->fcs = HDLC_FCS_INIT;
		return;
	}

	d->buf[d->len++] = b;
	d->fcs = fcs16(d->fcs, b);
}

void hdlc_decode(struct hdlc_decoder *d, const uint8_t *data, size_t len)
{
	for (size_t i = 0; i < len; i++) {
		hdlc_decode_byte(d, data[i]);
	}
}
